CREATE TABLE IF NOT EXISTS analytics.events
(
	`id` UUID,
	`client_id` String CODEC(ZSTD(1)),
	`event_name` LowCardinality(String) CODEC(ZSTD(1)),
	`anonymous_id` String CODEC(ZSTD(1)),
	`time` DateTime64(3, 'UTC') CODEC(Delta(8), ZSTD(1)),
	`session_id` String CODEC(ZSTD(1)),
	`referrer` Nullable(String) CODEC(ZSTD(1)),
	`url` String CODEC(ZSTD(1)),
	`path` String CODEC(ZSTD(1)),
	`title` Nullable(String) CODEC(ZSTD(1)),
	`ip` String CODEC(ZSTD(1)),
	`user_agent` String CODEC(ZSTD(1)),
	`browser_name` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`browser_version` Nullable(String) CODEC(ZSTD(1)),
	`os_name` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`os_version` Nullable(String) CODEC(ZSTD(1)),
	`device_type` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`device_brand` Nullable(String) CODEC(ZSTD(1)),
	`device_model` Nullable(String) CODEC(ZSTD(1)),
	`viewport_size` Nullable(String) CODEC(ZSTD(1)),
	`language` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`timezone` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`time_on_page` Nullable(Float32),
	`country` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`region` LowCardinality(Nullable(String)) CODEC(ZSTD(1)),
	`city` Nullable(String) CODEC(ZSTD(1)),
	`utm_source` Nullable(String) CODEC(ZSTD(1)),
	`utm_medium` Nullable(String) CODEC(ZSTD(1)),
	`utm_campaign` Nullable(String) CODEC(ZSTD(1)),
	`utm_term` Nullable(String) CODEC(ZSTD(1)),
	`utm_content` Nullable(String) CODEC(ZSTD(1)),
	`gclid` Nullable(String) CODEC(ZSTD(1)),
	`dom_ready_time` Nullable(Int32),
	`ttfb` Nullable(Int32),
	`request_time` Nullable(Int32),
	`render_time` Nullable(Int32),
	`scroll_depth` Nullable(Float32),
	`interaction_count` Nullable(Int16),
	`page_count` UInt8 DEFAULT 1,
	`properties` String CODEC(ZSTD(1)),
	`created_at` DateTime64(3, 'UTC') CODEC(Delta(8), ZSTD(1)),
	`timestamp` DateTime64(3) DEFAULT toDate(time) CODEC(Delta(8), ZSTD(1)),
	`profile_id` String DEFAULT '' CODEC(ZSTD(1)),
	INDEX idx_session_id session_id TYPE bloom_filter(0.01) GRANULARITY 1,
	INDEX idx_anonymous_id anonymous_id TYPE bloom_filter(0.01) GRANULARITY 1,
	INDEX idx_path path TYPE bloom_filter(0.02) GRANULARITY 1,
	INDEX idx_profile_id profile_id TYPE bloom_filter(0.01) GRANULARITY 1
)
ENGINE = ReplicatedMergeTree('/clickhouse/tables/{shard}/analytics_events', '{replica}')
PARTITION BY toYYYYMM(time)
ORDER BY (client_id, time, id)
SETTINGS index_granularity = 8192
